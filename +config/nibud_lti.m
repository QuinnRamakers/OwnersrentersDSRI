function L = nibud_lti(Y, rate, extra)
%NIBUD_LTI  Largest mortgage under the Nibud 2026 norms, as a multiple of income.
%
%   L = config.nibud_lti(Y, rate, extra)
%
%   Y      gross annual income of a single earner, euros
%   rate   annual mortgage rate at which the loan is tested
%   extra  true adds the EUR 17,000 increase that the Tijdelijke regeling
%          hypothecair krediet allows a single earner above the table's
%          lowest income
%
%   The financing-cost share (financieringslastpercentage) is read from the
%   Nibud table for borrowers below AOW age with deductible interest (box 1):
%   the row is the last income at or below Y, with incomes below the first row
%   on the first row, and the column is the rate bracket. The largest mortgage
%   is the loan whose 30-year monthly annuity at the rate costs that share of
%   income,
%       M = (flp * Y / 12) / a,   a = i (1+i)^360 / ((1+i)^360 - 1),   i = rate / 12,
%   plus the increase. This is the workbook's own calculator (sheet
%   toelichting) and reproduces its maximum-mortgage tables. Source: Nibud,
%   Financieringslastnormen 2026, bijlage, version 251110 (CALIBRATION.md).

arguments
    Y (1,1) double {mustBePositive}
    rate (1,1) double {mustBePositive}
    extra (1,1) logical
end

[inc, lo, flp] = table_box1();
i = rate / 12;
a = i * (1 + i)^360 / ((1 + i)^360 - 1);
share = flp(find(inc <= max(Y, inc(1)), 1, 'last'), find(lo <= rate, 1, 'last'));
M = share * Y / 12 / a + 17000 * (extra && Y > inc(1));
L = M / Y;
end

