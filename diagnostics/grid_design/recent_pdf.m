function recent_pdf(opts)
%RECENT_PDF  The step-7 figures and the grid study, in one PDF with a cover page per section.
%
%   recent_pdf()
%   recent_pdf(figdir=d, diagdir=d, pdf=file, start='...', owner_lines={...}, renter_lines={...})
%
%   Run from the repository root after diagnostics/step07/ruin_figures, the
%   grid-study solves and compare_grids. By default reads the figures of the
%   runs from p.b0 and writes
%   ladder/standard_16x16x10_gh5/grid_design/step7_grid_study.pdf. figdir and
%   diagdir point it at another set (report_b0 uses this); start describes the
%   starting savings on the cover; owner_lines and renter_lines replace the
%   gap tables on the section covers. Pages that have not been drawn are listed
%   on their section's cover page and skipped.

arguments
    opts.figdir (1,:) char = ''
    opts.diagdir (1,:) char = ''
    opts.pdf (1,:) char = ''
    opts.start (1,:) char = ['The simulations start with liquid savings of b0 = 0.079 years of gross income at 25 ' ...
        '(median deposits under 25).']
    opts.owner_lines cell = {}
    opts.renter_lines cell = {}
end

repo = fileparts(fileparts(fileparts(mfilename('fullpath'))));
cd(repo);
res = fullfile(repo, 'ladder', 'standard_16x16x10_gh5');
dg = opts.diagdir; if isempty(dg), dg = fullfile(res, 'diagnosis'); end
gd = opts.figdir;  if isempty(gd), gd = fullfile(res, 'grid_design'); end
pdf = opts.pdf;    if isempty(pdf), pdf = fullfile(gd, 'step7_grid_study.pdf'); end
if isfile(pdf), delete(pdf); end

owner_tab = opts.owner_lines;
if isempty(owner_tab)
    owner_tab = { ...
        'Largest gap to log-wealth 128x96 over ages 26-95 (mean equity share; bankrupt household-years; solve):', ...
        '  current 16x16 (as run)   0.72   5.5%     64 s     current 64x48       0.69   2.3%    649 s', ...
        '  log-wealth 32x32         0.58   0.59%   256 s     log-wealth 64x48    0.13   0.37%   658 s', ...
        '  power 2, 32x32           0.47   3.8%    223 s     power 2, 64x48      0.12   0.36%   616 s', ...
        '  reference 128x96           -    0.35%  2062 s'};
end
renter_tab = opts.renter_lines;
if isempty(renter_tab)
    renter_tab = { ...
        'Largest gap to log-wealth 128x96 over ages 26-95 (mean equity share; renters 25-39 at the consumption', ...
        'bound; solve):', ...
        '  current 16x16 (as run)   0.94    0%      79 s     current 64x48       0.72   29%     620 s', ...
        '  log-wealth 32x32         0.54    0.1%   206 s     log-wealth 64x48    0.64   32%     569 s', ...
        '  power 2, 32x32           0.72   11%     246 s     power 2, 64x48      0.57   40%     618 s', ...
        '  reference 128x96           -    78%    2206 s'};
end

sec = {};
sec(end+1, :) = {'1. Step 7 owner as run', { ...
    'Step 7: housing with the Table 1 dynamics, the mortgage and level placeholders, no correlations, no taxes', ...
    'or pension. Floor 1e-6 x income. The current grid (16x16) against the income axis doubled (32x16).', '', ...
    'Pages: bankruptcy rate by age; the value function along the no-savings line; the value function over', ...
    'savings and house value (full range, then houses up to 100 years of income); slices at the typical', ...
    'household''s savings with the grid each slice is interpolated from; the model''s mortgage payment against', ...
    'a fixed-rate mortgage (the same at any starting savings).'}, ...
    [cellfun(@(f) fullfile(dg, f), {'ruin_1_why.png', 'ruin_2_cliff.png', 'ruin_3_landscape.png', ...
    'ruin_3_landscape_zoom100.png', 'ruin_4_cut.png'}, 'UniformOutput', false), ...
    {fullfile(res, 'mortgage_07_owner_payment.png')}]};

pairs = {'_logwealth', 'log-wealth 16x16 and 32x32, against the current grid 16x16 and 32x32'; ...
         '_dense',     'log-wealth 32x32 and 64x48, against the current grid 32x32 and 64x48'; ...
         '_converged', 'log-wealth 64x48 and 128x96 (the reference), against the current grid 16x16 and 64x48'; ...
         '_power',     'power 2 at 32x32 and 64x48, against log-wealth 32x32 and 128x96 (the reference)'};
P = {}; L = {'Figures 1-3 for four pairs of grids, the step-7 owner, floor 1e-6:', ''};
for i = 1:size(pairs, 1)
    L{end+1} = sprintf('  %d. %s', i, pairs{i, 2}); %#ok<AGROW>
    for f = {'ruin_1_why', 'ruin_2_cliff', 'ruin_3_landscape', 'ruin_3_landscape_zoom100'}
        P{end+1} = fullfile(gd, [f{1} pairs{i, 1} '.png']); %#ok<AGROW>
    end
end
L = [L, {'', 'The grids: current = income share of wealth evenly spaced; log-wealth = evenly spaced in log wealth', ...
    'over income, denser between 2 and 60 years, house share clustered near "all in the house"; power 2 = the', ...
    'existing grid_pow and grid_pow_u2 at 2.'}];
sec(end+1, :) = {'2. Grid study, owner: figures 1-3 per pair of grids', L, P};

sec(end+1, :) = {'3. Grid study, owner: every grid against the 128x96 reference', [owner_tab, {'', ...
    'Pages: the robustness page (one row per grid family), the overlay with the income decomposition and the', ...
    'housing-cost burden, and the twelve-panel dashboards of the current 16x16, power 2 64x48 and the reference.'}], ...
    cellfun(@(f) fullfile(gd, f), {'robustness_owner_vs_logwealth_128x96.png', 'compare_owner.png', ...
    'dashboard_owner_uniform_16x16.png', 'dashboard_owner_power_64x48.png', ...
    'dashboard_owner_logwealth_128x96.png'}, 'UniformOutput', false)};

sec(end+1, :) = {'4. Grid study, renter', [{ ...
    'The same grids for the step-7 renter (rent 6% of a rent index of 4 x entry income, growing 0.99% a year).'}, ...
    renter_tab, {'', ...
    'Pages: the robustness page, the overlay, and the twelve-panel dashboards of power 2 64x48 and the reference.', ...
    'Figures 1-3 are owner figures (the bankruptcy edge uses the owner''s housing costs) and are not drawn here.'}], ...
    cellfun(@(f) fullfile(gd, f), {'robustness_renter_vs_logwealth_128x96.png', 'compare_renter.png', ...
    'dashboard_renter_power_64x48.png', 'dashboard_renter_logwealth_128x96.png'}, 'UniformOutput', false)};

cover(pdf, 'Step 7 (housing): the floor, bankruptcy and the state grid', { ...
    'Figures from 12-15 October 2026. Details and numbers: HANDOFF.md and docs/HANDOFF_2026-10-15.md.', '', ...
    opts.start, '', ...
    'All ratios are to gross household income (before tax, contributions and housing costs). The value function', ...
    'is shown as the constant yearly consumption, in years of income, worth as much as the situation; in brackets', ...
    'V itself, in units where a year of consuming one''s income is -1.', '', ...
    'Sections:', '  1. Step 7 owner as run', '  2. Grid study, owner: figures 1-3 per pair of grids', ...
    '  3. Grid study, owner: every grid against the 128x96 reference', '  4. Grid study, renter'});
for s = 1:size(sec, 1)
    have = cellfun(@isfile, sec{s, 3});
    L = sec{s, 2};
    if any(~have)
        [~, nm, ext] = cellfun(@fileparts, sec{s, 3}(~have), 'UniformOutput', false);
        L = [L, {'', 'Not drawn yet, skipped:'}, strcat({'  '}, nm, ext)]; %#ok<AGROW>
    end
    cover(pdf, sec{s, 1}, L);
    for f = sec{s, 3}(have), add_png(pdf, f{1}); end
end
fprintf('wrote %s (%.1f MiB)\n', pdf, dir(pdf).bytes / 2^20);
end

% ------------------------------------------------------------------------
function cover(pdf, ttl, lines)
fig = figure('Visible', 'off', 'Position', [0 0 1600 1000], 'Color', 'w');
ax = axes(fig, 'Position', [0.04 0.04 0.92 0.90]); axis(ax, 'off');
text(ax, 0, 1, ttl, 'FontSize', 20, 'FontWeight', 'bold', 'VerticalAlignment', 'top', 'Interpreter', 'none');
text(ax, 0, 0.93, lines, 'FontSize', 13, 'VerticalAlignment', 'top', 'Interpreter', 'none', 'FontName', 'Consolas');
exportgraphics(fig, pdf, 'Append', true, 'ContentType', 'image', 'Resolution', 100);
close(fig);
end

function add_png(pdf, file)
I = imread(file);
[h, w, ~] = size(I);
fig = figure('Visible', 'off', 'Position', [0 0 round(w / 1.3) round(h / 1.3)], 'Color', 'w');
ax = axes(fig, 'Position', [0 0 1 1]);
image(ax, I); axis(ax, 'image', 'off');
exportgraphics(fig, pdf, 'Append', true, 'ContentType', 'image', 'Resolution', 120);
close(fig);
end
