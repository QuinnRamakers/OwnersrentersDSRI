function S = steps()
%STEPS  The calibration ladder: a CGM core built up to the production model.
%
%   S = ladder.steps()
%
%   Each step is one change to the calibration, applied on top of the step it
%   builds on (its parent), and so on back to step 1. Step 1 replaces
%   production values with a Cocco, Gomes and Maenhout (2005) core inside this
%   model's time structure, and each later step restores one feature, so the
%   last step reproduces config.params().
%
%   The ladder branches at step 6, the baseline without housing:
%       6 -> 7 housing -> 7b annuity mortgage -> 8 housing correlations
%       6 -> 9 DC all bonds -> 10 DC all stocks -> 11 DC glide -> 12 AOW
%       8 -> 13 housing with AOW and DC -> 14 income tax -> 15 box 3
%         -> 16 house at the Nibud maximum mortgage
%         -> 17 maintenance on the purchase price -> 18 absorbing floor
%         -> 19 REIT in the DC fund
%   so housing and the DC pension are each checked on the baseline before
%   step 13 puts them together. Steps 7-15 keep the house at 4 times income,
%   steps 7-16 charge maintenance on the current house value, steps 1-17
%   have the yearly top-up instead of the absorbing floor, and steps 1-18 hold
%   no REIT (step 1 sets all three, since production has maintenance on the
%   purchase price, the floor and the REIT). The REIT's return moments are
%   production's on every step; with no share and no correlations nothing
%   reads them.
%
%   To change the calibration, edit a value in a step, or append a step at the
%   end -- for example a consumption-floor level or a housing multiple from
%   data. Fields:
%     name    identifier used in file names; unique
%     num     the number shown in titles, tables and file names, and taken by
%             ladder.run(8) and the like; '' numbers the step one after the
%             last numbered step. A step inserted after another takes its
%             number and a letter (7b), so the later steps keep theirs
%     label   one line for titles
%     note    where the values come from, one line
%     set     parameter overrides; every field must be a primitive of
%             config.params (config.params(false) lists them)
%     parent  name of the step this one builds on; '' for the step before it
%     vary    primitives to move one at a time around this step, each with
%             its values (ladder.sensitivity); empty for most steps
%
%   Fixed throughout, as deviations from CGM: entry at 25 rather than 20, a
%   terminal age of 100, Dutch unisex mortality, and no transitory income
%   shock (log income is a random walk with a permanent shock only).
%
%   Renters and owners share CGM's income process until the income step,
%   which gives each its own; from there on a step without housing is solved
%   for both (model.tenures_differ).

S = struct('name', {}, 'num', {}, 'label', {}, 'note', {}, 'set', {}, 'parent', {}, 'vary', {});

cgm_coef = [0.530339, 0.16818, -0.323371, 0.19704];
S(end+1) = step('cgm', 'CGM (2005) core', ...
    ['gamma 10, high-school income cubic, permanent shock std 0.1032, 68.2% ' ...
     'replacement at 65, r 2%, equity premium 4%, vol 15.7%, no income-stock ' ...
     'correlation; no housing, pension or taxes'], ...
    struct('gamma', 10, 'retirement_age', 65, 'income_source', 'poly', ...
           'income_coef', cgm_coef, 'income_coef_rent', cgm_coef, ...
           'sigma_l_log', 0.1032, 'sigma_l_log_rent', 0.1032, ...
           'replacement', 0.68212, 'r', 0.02, 'mu_S_level', 0.04, ...
           'sigma_S_level', 0.157, 'corr_SL', 0, 'corr_HL', 0, 'corr_HL_rent', 0, ...
           'corr_SH', 0, 'corr_SH_rent', 0, 'h_rule', 'none', 'kappa_base', 0, ...
           'tau_inc', 0, 'tau_cg_bond', 0, 'tau_cg_stock', 0, 'tau_wealth', 0, ...
           'tau_REIT', 0, 'reit_risky', 0, 'corr_RL', 0, 'corr_RS', 0, 'corr_RH', 0, 'corr_RH_rent', 0, ...
           'maint_on_purchase', false, 'c_min', 0));

S(end+1) = step('gamma5', 'Risk aversion 5', ...
    'Production value', ...
    struct('gamma', 5));

S(end+1) = step('retire67', 'Retirement at 67', ...
    'Statutory AOW age', ...
    struct('retirement_age', 67));

S(end+1) = step('income', 'Dutch income profile', ...
    ['DHS gross income (labour income and transfers), ages 25-65, owners and ' ...
     'renters pooled: an age cubic in 2020 euros raised to 2025 prices and a ' ...
     'permanent shock std of 0.0675 for both'], ...
    struct('income_source', 'dhs', ...
           'income_coef',      [6.9733, 0.20986, -0.3776, 0.2207], ...
           'income_coef_rent', [6.9733, 0.20986, -0.3776, 0.2207], ...
           'dhs_price_factor', 1.2516, ...
           'sigma_l_log', 0.0675, 'sigma_l_log_rent', 0.0675));

S(end+1) = step('market', 'Dutch financial market', ...
    ['Real NL 3-month interbank rate 1.15% (1982-2024); equity premium 4.56% ' ...
     'and volatility 21.61% (real, 2000-2024)'], ...
    struct('r', 0.0115, 'mu_S_level', 0.0456, 'sigma_S_level', 0.2161));

S(end+1) = step('corr_SL', 'Income-stock correlation', ...
    ['Correlation of the permanent income shock with the stock return, 0.04: ' ...
     'gross, pooled over all DHS households, 2002-2023'], ...
    struct('corr_SL', 0.04));

S(end+1) = step('housing', 'Housing', ...
    ['H at 4x entry income (placeholder). Owners: house prices 3.73% real, vol 8.35% ' ...
     '(NVM repeat sales, 1996-2024), 1.5% maintenance (placeholder), the mortgage ' ...
     'rate of 3.48% on the current house value. Renters: 5.6% rent on a rent ' ...
     'index growing 0.99% real, vol 1.79% (CBS regulated rents, 1983-2025). No ' ...
     'housing correlations'], ...
    struct('h_rule', 'fixed', 'h_fixed', 4, 'mu_H_level', 0.0373, 'sigma_H_level', 0.0835, ...
           'mu_R_level', 0.0099, 'sigma_R_level', 0.0179, 'mortgage', 'proportional'));

S(end+1) = step('annuity', 'Real annuity mortgage', ...
    '30-year real annuity at 3.48% on the purchase price', ...
    struct('mortgage', 'annuity'));
S(end).num = '7b';
% Maintenance on the purchase price instead of the current value: a test
S(end).vary = struct('maint_on_purchase', true);

S(end+1) = step('housing_corr', 'Housing correlations', ...
    ['Correlations of the H shock, gross income, 2002-2023: owners house price with ' ...
     'income 0.09 and stocks 0.24; renters rent with income 0.06 and stocks 0.43'], ...
    struct('corr_HL', 0.09, 'corr_HL_rent', 0.06, 'corr_SH', 0.24, 'corr_SH_rent', 0.43));

S(end+1) = step('dc_bonds', 'DC pension, all-bond fund', ...
    ['Built on step 6, without housing. Contributions of 18.6% of income above ' ...
     'the EUR 18,475 franchise, the fund all in bonds, annuitised at 67; ' ...
     'first-pillar income stays at CGM''s 68.2% of final income'], ...
    struct('kappa_base', 0.186, 'glide_cap', 0), 'corr_SL');

S(end+1) = step('dc_stocks', 'DC pension, all-stock fund', ...
    'The DC fund all in stocks at every age, and the annuity in retirement too', ...
    struct('glide_cap', 1, 'glide_span', 1, 'tau_decum', 1));

S(end+1) = step('dc_glide', 'DC pension, glide-path fund', ...
    ['The production fund: 80% stocks until 39, linear to 0% at 67, all bonds ' ...
     'in retirement'], ...
    struct('glide_cap', 0.8, 'glide_span', 35, 'tau_decum', []));

S(end+1) = step('aow', 'First pillar at the AOW', ...
    ['First-pillar income from 67 falls from CGM''s 68.2% to the AOW''s 30.7% ' ...
     'of final income (DNB, median first-pillar replacement rate)'], ...
    struct('replacement', 0.307));
% Illustrative lower and higher values, not calibration targets
S(end).vary = struct('replacement', [0.20 0.40], 'kappa_base', [0.10 0.30]);

S(end+1) = step('pension', 'Housing with AOW and DC pension', ...
    ['Built on step 8 (housing correlations): AOW replaces 30.7% of final ' ...
     'wage; DC contributions of 18.6% above the franchise, glide-path fund, ' ...
     'annuitised at 67'], ...
    struct('replacement', 0.307, 'kappa_base', 0.186), 'housing_corr');

S(end+1) = step('inctax', 'Income tax', ...
    'EET at 38.2% on wages, AOW and annuity payouts', ...
    struct('tau_inc', 0.382));

S(end+1) = step('box3', 'Box-3 tax', ...
    '36% on the liquid account''s returns, no loss offset', ...
    struct('tau_cg_bond', 0.36, 'tau_cg_stock', 0.36));

S(end+1) = step('nibud', 'House at the Nibud maximum mortgage', ...
    ['H at entry is the largest mortgage the Nibud 2026 norms allow at the tenure''s ' ...
     'gross income at 25 and the 3.48% mortgage rate (below AOW age, deductible ' ...
     'interest, with the EUR 17,000 increase): 4.52 times income for both tenures'], ...
    struct('h_rule', 'nibud'));

S(end+1) = step('maint_purchase', 'Maintenance on the purchase price', ...
    ['Owner maintenance of 1.5% of the purchase price instead of the current ' ...
     'house value (Quinn, 26 October 2026, for now); steps 7-16 keep the current value'], ...
    struct('maint_on_purchase', true));

S(end+1) = step('floor', 'Absorbing consumption floor at EUR 5,000', ...
    ['A household whose liquid resources fall below the floor goes bankrupt and ' ...
     'consumes the floor for life: EUR 5,000 a year at the owners'' median labour ' ...
     'income, the same share of income for both tenures (Quinn, 26 October 2026); ' ...
     'steps 1-17 keep the yearly top-up at 1e-6 of income'], ...
    struct('c_min', 5000));

S(end+1) = step('reit', 'REIT in the DC fund', ...
    ['Half the glide''s risky share in a listed real estate fund, half in stocks, ' ...
     'none in retirement (Quinn, 29 October 2026). Excess return 5.43%, vol ' ...
     '24.48% (Table 1); correlations with income 0.09, stocks 0.76, the house ' ...
     'price 0.17 for owners and the rent 0.59 for renters (Table 3, gross, ' ...
     'pooled); steps 1-18 hold no REIT'], ...
    struct('reit_risky', 0.5, 'corr_RL', 0.09, 'corr_RS', 0.76, 'corr_RH', 0.17, 'corr_RH_rent', 0.59));

n = 0;
for k = 1:numel(S)
    if isempty(S(k).num)
        n = n + 1;
        S(k).num = sprintf('%d', n);
    end
end
end

function s = step(name, label, note, set, parent)
if nargin < 5, parent = ''; end
s = struct('name', name, 'num', '', 'label', label, 'note', note, 'set', set, 'parent', parent, ...
           'vary', struct());
end
